-- Jalankan seluruh SQL ini di Supabase > SQL Editor > New query.
-- Profile otomatis dibuat saat akun Auth baru didaftarkan.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  username text not null unique,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.daily_goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  goal_date date not null default (now() at time zone 'Asia/Jakarta')::date,
  target_ml integer not null check (target_ml between 250 and 6000),
  glass_size_ml integer not null check (glass_size_ml between 50 and 1000),
  created_at timestamptz not null default now(),
  unique(user_id, goal_date)
);

create table if not exists public.water_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount_ml integer not null check (amount_ml between 1 and 2000),
  log_date date not null default (now() at time zone 'Asia/Jakarta')::date,
  consumed_at timestamptz not null default now()
);

create index if not exists water_logs_user_date_idx
  on public.water_logs(user_id, log_date);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, username)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    lower(coalesce(new.raw_user_meta_data ->> 'username', 'user_' || substr(new.id::text, 1, 8)))
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.daily_goals enable row level security;
alter table public.water_logs enable row level security;

-- Pengguna hanya dapat membaca dan memperbarui profil miliknya.
create policy "Users can read own profile"
on public.profiles for select
to authenticated
using (auth.uid() = id);

create policy "Users can update own profile"
on public.profiles for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id and role = 'user');

-- Pengguna hanya dapat mengelola target miliknya.
create policy "Users can read own goals"
on public.daily_goals for select
to authenticated
using (auth.uid() = user_id);

create policy "Users can insert own goals"
on public.daily_goals for insert
to authenticated
with check (auth.uid() = user_id);

create policy "Users can update own goals"
on public.daily_goals for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

-- Pengguna hanya dapat mengelola catatan minum miliknya.
create policy "Users can read own water logs"
on public.water_logs for select
to authenticated
using (auth.uid() = user_id);

create policy "Users can insert own water logs"
on public.water_logs for insert
to authenticated
with check (auth.uid() = user_id);

create policy "Users can delete own water logs"
on public.water_logs for delete
to authenticated
using (auth.uid() = user_id);

